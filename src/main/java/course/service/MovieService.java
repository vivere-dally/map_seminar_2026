package course.service;

import course.domain.Movie;
import course.domain.MovieSortField;
import course.lib.Page;
import course.lib.PageRequest;
import course.lib.Sort;
import course.repository.PagingRepository;

/**
 * The layer between the user interface and the repository: the controllers call
 * only the service, never the repository. The repository validates the movies.
 */
public class MovieService {
    private final PagingRepository<Long, Movie, MovieSortField> repository;

    /**
     *
     * @param repository - the movie repository; it validates the movies at save and update
     */
    public MovieService(PagingRepository<Long, Movie, MovieSortField> repository) {
        this.repository = repository;
    }

    /**
     *
     * @param pr   - the page to be returned
     * @param sort - the field and the direction of the sort
     * @return the movies on the page, sorted
     */
    public Page<Movie> findOnPage(PageRequest pr, Sort<MovieSortField> sort) {
        return repository.findOnPage(pr, sort);
    }

    /**
     *
     * @return the saved movie, with the id generated by the database
     * @throws course.domain.validators.ValidationException if the movie is not valid
     */
    public Movie addMovie(String title, String director, int year, int durationMinutes) {
        Movie movie = new Movie(title, director, year, durationMinutes);
        repository.save(movie);
        return movie;
    }

    /**
     *
     * @return the updated movie
     * @throws course.domain.validators.ValidationException if the new data is not valid
     * @throws IllegalArgumentException                     if there is no movie with the given id
     */
    public Movie updateMovie(Long id, String title, String director, int year, int durationMinutes) {
        Movie movie = new Movie(title, director, year, durationMinutes);
        movie.setId(id);
        if (repository.update(movie).isPresent())
            throw new IllegalArgumentException("Nu exista filmul cu id-ul " + id);
        return movie;
    }

    /**
     *
     * @return the deleted movie
     * @throws IllegalArgumentException if there is no movie with the given id
     */
    public Movie deleteMovie(Long id) {
        return repository.delete(id)
                .orElseThrow(() -> new IllegalArgumentException("Nu exista filmul cu id-ul " + id));
    }
}
